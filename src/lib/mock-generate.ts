import type { GenerateWorkInput, GeneratedWork, WorkflowType } from "./types";
import { getSavedMinutesForWorkflow, getWorkflowType } from "./workos-data";

export function mockGenerateWork(input: GenerateWorkInput): GeneratedWork {
  const workflow = getWorkflowType(input.workflowTypeId);
  const artifact = createArtifact(workflow, input.request);

  return {
    id: `work-${Date.now()}-${Math.random().toString(36).slice(2, 8)}`,
    workflowType: workflow.id,
    request: input.request.trim(),
    result: artifact.result,
    checklist: artifact.checklist,
    nextPrompt: artifact.nextPrompt,
    usedContextIds: input.usedContextIds,
    savedMinutes: getSavedMinutesForWorkflow(workflow.id),
    createdAt: new Date().toISOString(),
  };
}

